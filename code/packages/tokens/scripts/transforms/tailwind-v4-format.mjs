/**
 * Tailwind v4 CSS-first config format.
 * Per CD2 §8.2 — Tailwind v4 OKLCH-native palette; CSS-first config (Tailwind v4 paradigm).
 * 1:1 token-to-utility-class mapping (bg-vellum-25 / text-accent-prime / bg-sky-low / etc.).
 * Tailwind v4 supports per-hue chroma curves natively per CD2 Decision 2.
 */

const tokenPathToTailwindKey = (path) => {
  // tokens.color.platform.accent-prime → platform.accentPrime
  // tokens.color.dispatch.vellum.25 → dispatch.vellum.25
  // tokens.color.dispatch.lane.editorial.strong → dispatch.lane.editorial.strong
  return path
    .filter((segment) => segment !== 'color')
    .join('.');
};

const formatTailwindV4Config = ({ dictionary }) => {
  const colorTree = {};

  for (const token of dictionary.allTokens) {
    const key = tokenPathToTailwindKey(token.path);
    const value = token.$value ?? token.value;
    const segments = key.split('.');

    let cursor = colorTree;
    for (let i = 0; i < segments.length - 1; i++) {
      cursor[segments[i]] ??= {};
      cursor = cursor[segments[i]];
    }
    cursor[segments[segments.length - 1]] = value;
  }

  const colorTreeJson = JSON.stringify(colorTree, null, 2)
    .replace(/"([^"]+)":/g, '$1:');

  return [
    '/**',
    ' * PRIME DISpatch — Tailwind v4 CSS-first token config',
    ' * Generated by Style Dictionary v4 + DTCG 2025.10',
    ' * Ratified against CD2 (representation/visual-system/color.md)',
    ' * Do not hand-edit; regenerate via `npm run build`.',
    ' */',
    '',
    'import type { Config } from "tailwindcss";',
    '',
    'export default {',
    '  theme: {',
    '    extend: {',
    `      colors: ${colorTreeJson.replace(/\n/g, '\n      ')}`,
    '    }',
    '  }',
    '} satisfies Config;',
    ''
  ].join('\n');
};

export const registerTailwindV4Format = (StyleDictionary) => {
  StyleDictionary.registerFormat({
    name: 'prime/tailwind-v4-config',
    format: formatTailwindV4Config
  });
};
